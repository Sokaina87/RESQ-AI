CREATE TABLE IF NOT EXISTS scenarios (
  id TEXT PRIMARY KEY,
  disaster_type TEXT NOT NULL,
  location TEXT NOT NULL,
  title TEXT NOT NULL,
  created_at TEXT NOT NULL,
  active SMALLINT NOT NULL DEFAULT 0 CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS incidents (
  id TEXT PRIMARY KEY,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  location TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
  severity TEXT NOT NULL,
  people INTEGER NOT NULL DEFAULT 0 CHECK (people >= 0),
  description TEXT NOT NULL,
  status TEXT NOT NULL,
  created_at TEXT NOT NULL,
  validated SMALLINT NOT NULL DEFAULT 0 CHECK (validated IN (0, 1))
);

CREATE TABLE IF NOT EXISTS hospitals (
  id TEXT PRIMARY KEY,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
  beds INTEGER NOT NULL DEFAULT 0 CHECK (beds >= 0),
  er_load INTEGER NOT NULL DEFAULT 0 CHECK (er_load BETWEEN 0 AND 100),
  medicines TEXT NOT NULL DEFAULT 'À confirmer',
  patients INTEGER CHECK (patients >= 0),
  doctors_on_duty INTEGER CHECK (doctors_on_duty >= 0),
  medical_equipment TEXT NOT NULL DEFAULT 'À confirmer',
  status TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'manual',
  external_id TEXT
);

CREATE TABLE IF NOT EXISTS ambulances (
  id TEXT PRIMARY KEY,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
  team TEXT NOT NULL,
  capacity INTEGER NOT NULL DEFAULT 1 CHECK (capacity > 0),
  equipment TEXT NOT NULL DEFAULT 'À confirmer',
  status TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'manual',
  external_id TEXT
);

ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'manual';
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS external_id TEXT;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS patients INTEGER CHECK (patients >= 0);
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS doctors_on_duty INTEGER CHECK (doctors_on_duty >= 0);
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS medical_equipment TEXT NOT NULL DEFAULT 'À confirmer';
ALTER TABLE ambulances ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'manual';
ALTER TABLE ambulances ADD COLUMN IF NOT EXISTS external_id TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS hospitals_external_unique_idx
  ON hospitals (scenario_id, external_id) WHERE external_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ambulances_external_unique_idx
  ON ambulances (scenario_id, external_id) WHERE external_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS geocode_cache (
  query_key TEXT PRIMARY KEY,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  display_name TEXT NOT NULL,
  cached_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS osm_poi_cache (
  query_key TEXT PRIMARY KEY,
  payload TEXT NOT NULL,
  cached_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS simulation_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  inputs TEXT NOT NULL,
  result TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS incident_media (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id TEXT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
  media_type TEXT NOT NULL CHECK (media_type IN ('image', 'voice_transcript')),
  content TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS experts (
  id TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  specialty TEXT NOT NULL,
  availability TEXT NOT NULL DEFAULT 'À confirmer',
  languages TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  experience_years INTEGER NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
  contact TEXT,
  demo SMALLINT NOT NULL DEFAULT 0 CHECK (demo IN (0, 1))
);

CREATE TABLE IF NOT EXISTS risk_assessments (
  id TEXT PRIMARY KEY,
  disaster_type TEXT NOT NULL,
  location TEXT NOT NULL,
  risk_score INTEGER NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
  risk_level TEXT NOT NULL,
  assessment TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS recovery_reports (
  id TEXT PRIMARY KEY,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  report TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS recovery_lessons (
  id TEXT PRIMARY KEY,
  report_id TEXT NOT NULL REFERENCES recovery_reports(id) ON DELETE CASCADE,
  scenario_id TEXT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  disaster_type TEXT NOT NULL,
  location TEXT NOT NULL,
  insight TEXT NOT NULL,
  risk_increment INTEGER NOT NULL CHECK (risk_increment BETWEEN 0 AND 20),
  validated SMALLINT NOT NULL DEFAULT 0 CHECK (validated IN (0, 1)),
  created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS incidents_scenario_created_idx ON incidents (scenario_id, created_at DESC);
CREATE INDEX IF NOT EXISTS hospitals_scenario_idx ON hospitals (scenario_id);
CREATE INDEX IF NOT EXISTS ambulances_scenario_idx ON ambulances (scenario_id);
CREATE INDEX IF NOT EXISTS simulations_scenario_idx ON simulation_runs (scenario_id, created_at DESC);
CREATE INDEX IF NOT EXISTS incident_media_incident_idx ON incident_media (incident_id);
CREATE INDEX IF NOT EXISTS experts_specialty_idx ON experts (specialty, availability);
CREATE INDEX IF NOT EXISTS risk_assessments_created_idx ON risk_assessments (created_at DESC);
CREATE INDEX IF NOT EXISTS recovery_reports_scenario_idx ON recovery_reports (scenario_id, created_at DESC);
CREATE INDEX IF NOT EXISTS recovery_lessons_region_idx ON recovery_lessons (disaster_type, location, validated);
